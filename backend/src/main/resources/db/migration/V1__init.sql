CREATE TABLE audit_event (
    event_id       VARCHAR(36)  PRIMARY KEY,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id       VARCHAR(64),
    action_name    VARCHAR(60)  NOT NULL,
    entity_type    VARCHAR(60)  NOT NULL,
    entity_id      VARCHAR(64),
    previous_value VARCHAR(4000),
    new_value      VARCHAR(4000),
    reason         VARCHAR(1000),
    project_id     VARCHAR(64)
);
CREATE INDEX idx_audit_time ON audit_event (occurred_at);
CREATE INDEX idx_audit_entity ON audit_event (entity_type, entity_id);

CREATE TABLE notification (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id         VARCHAR(64)  NOT NULL REFERENCES app_user (id),
    kind                 VARCHAR(40)  NOT NULL,
    message              VARCHAR(1000) NOT NULL,
    related_operation_id VARCHAR(64),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at              TIMESTAMP WITH TIME ZONE,
    delivery_status      VARCHAR(20)  NOT NULL,
    delivery_error       VARCHAR(500)
);
CREATE INDEX idx_notification_recipient ON notification (recipient_id, created_at);

CREATE TABLE operation_report (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id     VARCHAR(64)  NOT NULL REFERENCES operation (id),
    user_id          VARCHAR(64)  NOT NULL,
    report_type      VARCHAR(30)  NOT NULL,
    progress_percent INTEGER,
    note             VARCHAR(2000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_report_operation ON operation_report (operation_id);

CREATE TABLE assignment_run (
    id             VARCHAR(36)  PRIMARY KEY,
    requested_mode VARCHAR(20)  NOT NULL,
    effective_mode VARCHAR(20)  NOT NULL,
    fallback       BOOLEAN      NOT NULL,
    model          VARCHAR(100),
    summary        VARCHAR(2000),
    warnings       VARCHAR(4000),
    unassigned     VARCHAR(4000),
    requested_by   VARCHAR(64)  NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_ms    BIGINT       NOT NULL,
    input_tokens   BIGINT,
    output_tokens  BIGINT
);

CREATE TABLE assignment_proposal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        VARCHAR(36)  NOT NULL REFERENCES assignment_run (id),
    operation_id  VARCHAR(64)  NOT NULL REFERENCES operation (id),
    user_id       VARCHAR(64)  NOT NULL REFERENCES app_user (id),
    source        VARCHAR(20)  NOT NULL,
    reason        VARCHAR(2000),
    planned_start TIMESTAMP WITH TIME ZONE,
    planned_end   TIMESTAMP WITH TIME ZONE,
    status        VARCHAR(20)  NOT NULL,
    decision_note VARCHAR(500),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at    TIMESTAMP WITH TIME ZONE,
    decided_by    VARCHAR(64)
);
CREATE INDEX idx_proposal_status ON assignment_proposal (status);

CREATE TABLE import_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imported_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id     VARCHAR(64)  NOT NULL,
    file_name    VARCHAR(300),
    file_format  VARCHAR(20),
    status       VARCHAR(20)  NOT NULL,
    error_count  INTEGER      NOT NULL,
    summary      VARCHAR(2000),
    details      VARCHAR(9000)
);
