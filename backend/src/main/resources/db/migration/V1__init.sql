-- AISO MVP 0.1 schema. Business identifiers (Resource_ID, Operation_ID, ...) are the primary keys.

CREATE TABLE app_user (
    id                   VARCHAR(64)  PRIMARY KEY,
    full_name            VARCHAR(200) NOT NULL,
    user_role            VARCHAR(20)  NOT NULL,
    messenger_id         VARCHAR(100),
    active               BOOLEAN      NOT NULL,
    contact_info         VARCHAR(300),
    password_hash        VARCHAR(100) NOT NULL,
    must_change_password BOOLEAN      NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE work_resource (
    id                  VARCHAR(64)  PRIMARY KEY,
    name                VARCHAR(200) NOT NULL,
    resource_type       VARCHAR(100),
    responsible_user_id VARCHAR(64) REFERENCES app_user (id),
    capacity            INTEGER      NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    description         VARCHAR(1000)
);

CREATE TABLE item (
    id                   VARCHAR(64)  PRIMARY KEY,
    name                 VARCHAR(200) NOT NULL,
    quantity             DOUBLE PRECISION NOT NULL,
    unit                 VARCHAR(30),
    supply_type          VARCHAR(50),
    related_operation_id VARCHAR(64),
    description          VARCHAR(1000)
);

CREATE TABLE operation (
    id                  VARCHAR(64)  PRIMARY KEY,
    name                VARCHAR(300) NOT NULL,
    item_id             VARCHAR(64) REFERENCES item (id),
    resource_id         VARCHAR(64)  NOT NULL REFERENCES work_resource (id),
    responsible_user_id VARCHAR(64) REFERENCES app_user (id),
    preparation_time    DOUBLE PRECISION NOT NULL,
    transport_time      DOUBLE PRECISION NOT NULL,
    setup_time          DOUBLE PRECISION NOT NULL,
    direct_time         DOUBLE PRECISION NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    assigned_user_id    VARCHAR(64) REFERENCES app_user (id),
    block_reason        VARCHAR(1000),
    status_before_block VARCHAR(20),
    progress_percent    INTEGER      NOT NULL,
    planned_start       TIMESTAMP WITH TIME ZONE,
    planned_end         TIMESTAMP WITH TIME ZONE,
    assigned_at         TIMESTAMP WITH TIME ZONE,
    started_at          TIMESTAMP WITH TIME ZONE,
    completed_at        TIMESTAMP WITH TIME ZONE,
    completion_approved BOOLEAN      NOT NULL,
    completion_approved_by VARCHAR(64),
    cancel_reason       VARCHAR(1000),
    description         VARCHAR(1000),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    version             BIGINT       NOT NULL
);
CREATE INDEX idx_operation_status ON operation (status);
CREATE INDEX idx_operation_assigned ON operation (assigned_user_id);

CREATE TABLE predecessor (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id    VARCHAR(64)  NOT NULL REFERENCES operation (id),
    predecessor_id  VARCHAR(64)  NOT NULL REFERENCES operation (id),
    dependency_type VARCHAR(20)  NOT NULL,
    start_condition VARCHAR(300),
    mandatory       BOOLEAN      NOT NULL,
    description     VARCHAR(500),
    CONSTRAINT uq_predecessor UNIQUE (operation_id, predecessor_id)
);

CREATE TABLE system_setting (
    id                          INTEGER PRIMARY KEY,
    project_id                  VARCHAR(64),
    project_name                VARCHAR(200),
    owner_id                    VARCHAR(64),
    manager_id                  VARCHAR(64),
    messenger_platform          VARCHAR(30)  NOT NULL,
    system_status               VARCHAR(20)  NOT NULL,
    data_version                VARCHAR(50),
    configuration_version       INTEGER      NOT NULL,
    assignment_mode             VARCHAR(20)  NOT NULL,
    max_active_tasks_per_user   INTEGER      NOT NULL,
    require_completion_approval BOOLEAN      NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE NOT NULL
);
